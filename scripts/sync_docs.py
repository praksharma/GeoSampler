"""Project canonical Markdown into focused Zensical pages; --check never writes."""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
PAGES = [
    ('guide/getting-started.md', 'Install and create your first dataset', ['Installation and first dataset']),
    ('guide/workspace.md', 'Workspace and visibility', ['Desktop foundation', 'Toolbar and visibility', 'Face and sampled-area context menus']),
    ('guide/geometry.md', 'Geometry import and selection', ['Geometry import and selection', 'Neutral CAD import']),
    ('guide/regions.md', 'Boundary regions', ['User-defined boundary regions']),
    ('guide/sampling.md', 'Sampling and accuracy', ['Sampling', 'Geometry and accuracy', 'Previews and generation lifecycle']),
    ('guide/normals.md', 'Boundary normals', ['Boundary normals']),
    ('guide/datasets.md', 'Datasets and editing', ['Sampled Areas tree', 'Edit a sampled area']),
    ('guide/projects.md', 'Projects and recovery', ['Save and reopen projects']),
    ('guide/parametrisation.md', 'Translation previews', ['Parametrisation: first translation slice']),
    ('guide/graphics.md', 'Graphics troubleshooting', ['NVIDIA rendering on Linux/Wayland']),
    ('reference/exports.md', 'NetCDF, NPZ and xarray', ['Exporting samples', 'Schema version 2']),
    ('development/architecture.md', 'Architecture and scope', ['Architecture', 'Agreed product scope']),
    ('development/testing.md', 'Testing and validation', ['Development validation', 'Foundation validation record']),
    ('development/performance.md', 'Sampling performance and CPU modes', ['Sampling performance and CPU modes']),
    ('development/release.md', 'Development preview and release checks', ['Development preview and release checks']),
    ('development/documentation.md', 'Maintaining the documentation', ['Documentation site']),
    ('reference/attribution.md', 'Attribution and licences', ['Provenance']),
]


def sections(text):
    """Split level-two/three headings outside fenced code blocks."""
    result = {}
    title, body, fence = None, [], None
    for line in text.splitlines(keepends=True):
        marker = re.match(r'^ {0,3}(`{3,}|~{3,})', line)
        if marker:
            token = marker[1]
            if fence is None:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence):
                fence = None
            if title is not None: body.append(line)
            continue
        heading = re.match(r'^#{2,3} (.+?)\s*$', line) if fence is None else None
        if heading:
            if title is not None: result[title] = ''.join(body).strip()
            title, body = heading[1], []
            if title in result: raise ValueError('Duplicate guide heading: ' + title)
        elif title is not None:
            body.append(line)
    if title is not None: result[title] = ''.join(body).strip()
    return result



def page_body(text):
    # Level-four guide subsections become level-two headings on their own page.
    result, fence = [], None
    for line in text.splitlines(keepends=True):
        marker = re.match(r'^ {0,3}(`{3,}|~{3,})', line)
        if marker:
            token = marker[1]
            if fence is None: fence = token
            elif token[0] == fence[0] and len(token) >= len(fence): fence = None
        elif fence is None:
            line = re.sub(r'^(#{4,6}) ', lambda match: '#' * (len(match[1])-2) + ' ', line)
        result.append(line)
    return ''.join(result)


def generated_pages():
    parts = sections((ROOT / 'GUIDE.md').read_text())
    assigned = [name for _, _, names in PAGES for name in names]
    if len(set(assigned)) != len(assigned): raise ValueError('Guide section mapped more than once.')
    missing, stale = set(parts) - set(assigned), set(assigned) - set(parts)
    if missing or stale:
        raise ValueError(f'Guide page map needs updating. Unmapped: {sorted(missing)}; missing headings: {sorted(stale)}')
    pages = {}
    for path, title, names in PAGES:
        content = f'<!-- Generated by scripts/sync_docs.py from GUIDE.md; edit the source. -->\n\n# {title}\n\n'
        for index, name in enumerate(names):
            if index: content += f'## {name}\n\n'
            content += page_body(parts[name]) + '\n\n'
        pages[path] = content.rstrip() + '\n'
    pages['reference/attribution.md'] += '\n' + re.sub(r'^(#{1,5}) ', r'\1# ', (ROOT / 'THIRD_PARTY.md').read_text(), flags=re.MULTILINE)
    pages['reference/attribution.md'] += '\n[Read the full GeoSampler licence](../assets/licenses/AGPL-3.0.txt).\n'
    pages['assets/licenses/AGPL-3.0.txt'] = (ROOT / 'LICENSE').read_text()
    pages['development/roadmap.md'] = '<!-- Generated by scripts/sync_docs.py from TODO.md; edit the source. -->\n\n' + (ROOT / 'TODO.md').read_text()
    return pages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    pages = generated_pages()
    changed = []
    for name, content in pages.items():
        path = ROOT / 'docs' / name
        if path.is_file() and path.read_text() == content: continue
        changed.append(name)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.check and changed:
        print('Documentation is missing or stale; run python scripts/sync_docs.py:', file=sys.stderr)
        print('\n'.join(changed), file=sys.stderr)
        return 1
    print(f'{len(pages)} documentation files ' + ('verified.' if args.check else f'synchronised ({len(changed)} updated).'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
